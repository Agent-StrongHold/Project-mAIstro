"""Internal blob refs vs. browser-resolvable presentation URLs (#2311).

The governed image egress stores generated bytes in ``canvas_blobs`` and hands
back the row's id — an internal, immutable blob *reference*. That reference is
durable storage addressing, not a URL a browser can load: ``<img src>`` with a
bare UUID renders nothing. The two identities are deliberately distinct, and
this module is the one seam that maps between them:

- storage (``layer.image_path``, ``job.result_paths``, Invocation ``ref``)
  keeps holding the raw reference — the durable, restart-stable identity the
  executor and the governed egress reason about;
- the HTTP boundary (``maistro_server.api.canvas``) converts a reference into
  the presentation path ``GET /v2/canvas/blobs/{blob_id}`` when it serializes
  an image for a client, so the browser never sees a bare UUID as a URL.

The conversion is total and pass-through: anything that is not a governed
blob reference (a ``data:`` URL, an ``http(s)`` URL, a filesystem path left
over from the standalone app) comes back unchanged, so callers can apply it
to every ``image_path`` without knowing which kind of value a layer carries.
"""

from __future__ import annotations

import uuid

#: The one authorized byte-serving presentation path for a Canvas blob. It is
#: served by the maistro-server ``/v2/canvas`` boundary under the same
#: authentication and Workspace-membership authorization as every other route
#: (ADR-045: the boundary wraps Canvas; there is no second, unscoped bytes
#: endpoint).
BLOB_URL_PREFIX = "/v2/canvas/blobs/"

_BLOB_URL_PREFIX_LEN = len(BLOB_URL_PREFIX)


def is_blob_ref(value: object) -> bool:
    """Whether ``value`` is a governed ``canvas_blobs`` reference.

    The store mints references with :func:`uuid.uuid4`, so the shape check is
    a strict canonical-UUID parse: URLs and data URLs never parse, and a
    non-canonical UUID spelling is not a reference this store ever wrote.
    """
    if not isinstance(value, str):
        return False
    try:
        return str(uuid.UUID(value)) == value
    except ValueError:
        return False


def is_presentation_url(value: object) -> bool:
    """Whether ``value`` is already this seam's presentation path."""
    if not isinstance(value, str):
        return False
    if not value.startswith(BLOB_URL_PREFIX):
        return False
    return is_blob_ref(value[_BLOB_URL_PREFIX_LEN:])


def presentation_path(ref: str) -> str:
    """The browser-resolvable presentation path for one blob reference."""
    if not is_blob_ref(ref):
        msg = f"not a governed Canvas blob reference: {ref!r}"
        raise ValueError(msg)
    return f"{BLOB_URL_PREFIX}{ref}"


def to_presentation_url(value: str | None) -> str | None:
    """Map a stored image value to what an ``<img src>`` can load.

    A governed blob reference becomes its presentation path; every other
    value (data URL, remote URL, path) is already loadable and passes through
    untouched. ``None`` stays ``None``.
    """
    if value is None:
        return None
    if is_blob_ref(value):
        return presentation_path(value)
    return value


__all__ = [
    "BLOB_URL_PREFIX",
    "is_blob_ref",
    "is_presentation_url",
    "presentation_path",
    "to_presentation_url",
]
