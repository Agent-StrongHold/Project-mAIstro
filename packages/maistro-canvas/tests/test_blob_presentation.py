"""Blob reference vs. presentation URL — the one conversion seam (#2311).

The governed image egress stores generated bytes under internal
``canvas_blobs`` references. Those references are durable storage addressing,
not browser-resolvable URLs; ``blob_presentation`` is the seam that keeps the
two identities distinct and converts at the HTTP boundary. These tests pin
the classification (a reference is a canonical UUID; URLs, data URLs and
paths never are), the mapping, and the pass-through behavior the design
serializer relies on.
"""

from __future__ import annotations

import uuid

import pytest

from maistro_canvas.canvas.blob_presentation import (
    BLOB_URL_PREFIX,
    is_blob_ref,
    is_presentation_url,
    presentation_path,
    to_presentation_url,
)


def _ref() -> str:
    return str(uuid.uuid4())


class TestIsBlobRef:
    def test_a_store_minted_reference_is_one(self) -> None:
        assert is_blob_ref(_ref()) is True

    def test_a_data_url_is_not(self) -> None:
        assert is_blob_ref("data:image/png;base64,aGVsbG8=") is False

    def test_a_remote_url_is_not(self) -> None:
        assert is_blob_ref("https://cdn.example.com/img.png") is False
        assert is_blob_ref("http://localhost:8000/v2/canvas/blobs/x") is False

    def test_a_relpath_is_not(self) -> None:
        assert is_blob_ref("assets/backgrounds/sky.png") is False
        assert is_blob_ref("") is False

    def test_non_canonical_uuid_spellings_are_not(self) -> None:
        # The store mints canonical hyphenated ids; other spellings are not
        # references it ever wrote, and misclassifying one would rewrite an
        # unrelated image value into a blob URL.
        value = uuid.uuid4()
        assert is_blob_ref(value.hex) is False  # no dashes
        assert is_blob_ref(f"urn:uuid:{value}") is False
        assert is_blob_ref(str(value).upper()) is False  # non-canonical case
        assert is_blob_ref(None) is False  # type: ignore[arg-type]
        assert is_blob_ref(42) is False  # type: ignore[arg-type]


class TestPresentationMapping:
    def test_a_reference_maps_to_the_one_authorized_path(self) -> None:
        ref = _ref()
        assert presentation_path(ref) == f"{BLOB_URL_PREFIX}{ref}"
        assert to_presentation_url(ref) == f"{BLOB_URL_PREFIX}{ref}"

    def test_a_non_reference_passes_through_untouched(self) -> None:
        for value in (
            "data:image/png;base64,aGVsbG8=",
            "https://cdn.example.com/img.png",
            "assets/backgrounds/sky.png",
        ):
            assert to_presentation_url(value) == value

    def test_none_stays_none(self) -> None:
        assert to_presentation_url(None) is None

    def test_a_non_reference_cannot_be_forced_into_a_blob_path(self) -> None:
        with pytest.raises(ValueError, match="not a governed Canvas blob reference"):
            presentation_path("https://cdn.example.com/img.png")

    def test_the_seam_recognises_its_own_output(self) -> None:
        ref = _ref()
        path = presentation_path(ref)
        assert is_presentation_url(path) is True
        assert is_presentation_url(f"{BLOB_URL_PREFIX}{uuid.uuid4().hex}") is False
        assert is_presentation_url(ref) is False
