def _expected_wire(cause: CancellationCause | None) -> dict[str, Any]:
    """The exact wire for the cause fixture, hand-built from the frozen baseline."""
    wire = dict(_LEGACY_PAYLOAD)
    if cause is CancellationCause.REQUESTED:
        wire["error"] = _REQUESTED_ERROR
    elif cause is CancellationCause.RECOVERED:
        wire["error"] = _RECOVERED_ERROR
        wire["execution_lease"] = _RECOVERED_LEASE_WIRE
    if cause is not None:
        wire["cancellation_cause"] = cause.value
    return wire


