def _evidence_attempt(cause: CancellationCause | None) -> Attempt:
    """A terminal Attempt whose physical evidence is deliberately non-finite.

    With a typed cause the Attempt is the CANCELLED carrier; without one it is
    the plain completed evidence row. Either way the codec must restore the
    same non-finite evidence.
    """
    fields: dict[str, Any] = {
        "attempt_id": "attempt-evidence-fixed",
        "node_run_id": "node-evidence-fixed",
        "ordinal": 1,
        "status": AttemptStatus.COMPLETED,
        "executor_id": "worker-codec-fixed",
        "execution_lease": None,
        "created_at": _CREATED,
        "started_at": _STARTED,
        "finished_at": _FINISHED,
        "deadline_at": None,
        "resume_checkpoint_id": None,
        "result": _NON_FINITE_RESULT,
        "error": None,
        "metrics": _NON_FINITE_METRICS,
    }
    if cause is not None:
        fields["status"] = AttemptStatus.CANCELLED
        fields["cancellation_cause"] = cause
    return Attempt.model_validate(fields)


def _durable_record(cause: CancellationCause | None) -> DurableRunRecord:
    """A valid DurableRunRecord with true Run/NodeRun/Attempt linkage.

    Two NodeRuns (consecutive ordinals), each with one Attempt (consecutive
    per NodeRun): the cancelled cause carrier and a completed Attempt holding
    finite physical evidence. Deliberately finite-only evidence at the nested
    positions: this leaf proves cause/lineage at the record level and the
    non-finite unit at the Attempt level the stores actually persist.
    """
    graph = Graph(
        graph_id="graph-codec-fixed",
        workspace_id="ws-codec-fixed",
        project_id="project-codec-fixed",
        name="cancellation cause codec proof",
        nodes=[
            Node(node_id="cancel-node", node_type="test"),
            Node(node_id="evidence-node", node_type="test"),
        ],
    )
    run = Run(
        run_id="run-codec-fixed",
        workspace_id="ws-codec-fixed",
        project_id="project-codec-fixed",
        graph=GraphSnapshot.from_graph(graph),
        status=RunStatus.RUNNING,
        actor_principal_id="test:codec-proof",
        created_at=_CREATED,
        updated_at=_STARTED,
        started_at=_STARTED,
    )
    state = GraphExecutionState(run_id="run-codec-fixed", active_node_ids=("evidence-node",))
    node_runs = (
        NodeRun(
            node_run_id="node-codec-fixed",
            run_id="run-codec-fixed",
            node_id="cancel-node",
            ordinal=1,
            status=RunStatus.CANCELLED,
            created_at=_CREATED,
            updated_at=_FINISHED,
            started_at=_STARTED,
            finished_at=_FINISHED,
        ),
        NodeRun(
            node_run_id="node-evidence-fixed",
            run_id="run-codec-fixed",
            node_id="evidence-node",
            ordinal=2,
            status=RunStatus.RUNNING,
            created_at=_CREATED,
            updated_at=_CREATED,
            started_at=_STARTED,
        ),
    )
    completed = Attempt(
        attempt_id="attempt-evidence-fixed",
        node_run_id="node-evidence-fixed",
        ordinal=1,
        status=AttemptStatus.COMPLETED,
        executor_id="worker-codec-fixed",
        created_at=_CREATED,
        started_at=_STARTED,
        finished_at=_FINISHED,
        result={"answer": 42, "ratio": 1.5},
        metrics={"count": 2, "optional": None},
    )
    return DurableRunRecord(
        run=run,
        graph_state=state,
        node_runs=node_runs,
        attempts=(_fixture_attempt(cause), completed),
        version=1,
    )


class _Envelope(BaseModel):
    """Minimal parent whose `model_dump(mode="json")` must run each child serializer."""

    attempts: list[Attempt]


def _assert_baseline_wire(payload: dict[str, Any], cause: CancellationCause | None) -> None:
    """The payload matches the hand-frozen baseline exactly, cause key included.

    Never an expected value generated by the serializer under test: the
    baseline is the frozen legacy-shaped fixture, and the typed cause is the
    only key allowed to differ from it.
    """
    if cause is None:
        assert "cancellation_cause" not in payload
    else:
        assert payload["cancellation_cause"] == cause.value
    rest = {key: value for key, value in payload.items() if key != "cancellation_cause"}
    baseline = _expected_wire(cause)
    baseline.pop("cancellation_cause", None)
    assert rest == baseline


@pytest.mark.parametrize("transport", _TRANSPORT_IDS)
@pytest.mark.parametrize("cause", _CAUSE_PARAMS)
def test_cause_round_trips_through_canonical_evidence_json(
    cause: CancellationCause | None, transport: str
) -> None:
    """A typed cause keeps its exact wire value; an unknown one keeps no key.

    Everything around the cause compares exactly against the hand-frozen
    legacy-shaped baseline, so a serializer that dropped a non-null cause,
    emitted null for unknown, applied a global exclude_none, or rewrote any
    other field would fail here rather than pass silently.
    """
    attempt = _fixture_attempt(cause)
    restored = _codec_round_trip(Attempt, attempt, transport)
    assert restored == attempt

    payload = payload_of(attempt)
    _assert_baseline_wire(payload, cause)
    _assert_baseline_wire(json.loads(json_of(attempt)), cause)

    # Representative include/exclude selections keep their existing semantics:
    # the codec never forces the cause into a selection that did not ask for
    # it, and excluding an unrelated field never drops a selected cause.
    included = attempt.model_dump(mode="json", include={"attempt_id", "status", "result"})
    assert included == {
        "attempt_id": "attempt-codec-fixed",
        "status": "cancelled",
        "result": None,
    }
    excluded = attempt.model_dump(mode="json", exclude={"error"})
    assert excluded == {
        key: value for key, value in _expected_wire(cause).items() if key != "error"
    }
    selected = attempt.model_dump(mode="json", include={"cancellation_cause", "result"})
    if cause is None:
        assert selected == {"result": None}
    else:
        assert selected == {"cancellation_cause": cause.value, "result": None}


@pytest.mark.parametrize(
    "explicit_null",
    [pytest.param(False, id="absent"), pytest.param(True, id="explicit-null")],
)
def test_unknown_cause_is_omitted_without_dropping_other_none(explicit_null: bool) -> None:
    """Missing or null input hydrates to an unknown cause and emits no key.

    The output key is absent at the root and at the nested Attempt position of
    a parent `model_dump(mode="json")` — which is only honest if the child
    serializer actually ran — while every other explicit null and the empty
    metrics mapping survive exactly against the frozen baseline.
    """
    fields: dict[str, Any] = dict(_fixture_attempt(None).model_dump())
    if explicit_null:
        fields["cancellation_cause"] = None
    attempt = Attempt.model_validate(fields)

    payload = payload_of(attempt)
    assert "cancellation_cause" not in payload
    assert payload == _LEGACY_PAYLOAD
    assert json.loads(json_of(attempt)) == json.loads(_LEGACY_JSON)
    for key in ("execution_lease", "deadline_at", "resume_checkpoint_id", "result", "error"):
        assert payload[key] is None
    assert payload["metrics"] == {}
    assert payload["ordinal"] == 1
    assert payload["finished_at"] == "2026-10-03T12:00:10Z"

    nested = _Envelope(attempts=[attempt]).model_dump(mode="json")
    assert "cancellation_cause" not in nested["attempts"][0]
    assert nested["attempts"][0] == _LEGACY_PAYLOAD
    assert "cancellation_cause" not in payload_of(_Envelope(attempts=[attempt]))["attempts"][0]


@pytest.mark.parametrize("cause", _CAUSE_PARAMS)
def test_nested_durable_record_preserves_cause_and_lineage(
    cause: CancellationCause | None,
) -> None:
    """The record-level canonical codec keeps the cause and the true lineage.

    Round-tripping a DurableRunRecord through `payload_of`/`model_of` and
    through the parent `model_dump(mode="json")` preserves identities,
    ordinals, statuses and timestamps, and the nested Attempt position carries
    (or omits) the cause exactly as the root position does.
    """
    record = _durable_record(cause)
    restored = model_of(DurableRunRecord, payload_of(record))
    assert restored == record
    assert model_of(DurableRunRecord, json_of(record)) == record

    parent_dump = record.model_dump(mode="json")
    cancelled = parent_dump["attempts"][0]
    completed = parent_dump["attempts"][1]
    _assert_baseline_wire(cancelled, cause)
    assert completed["result"] == {"answer": 42, "ratio": 1.5}
    assert completed["metrics"] == {"count": 2, "optional": None}

    # Lineage: identities and ordinals survive as persisted facts.
    assert restored.run_id == "run-codec-fixed"
    assert [node.node_run_id for node in restored.node_runs] == [
        "node-codec-fixed",
        "node-evidence-fixed",
    ]
    assert [node.ordinal for node in restored.node_runs] == [1, 2]
    assert [(attempt.node_run_id, attempt.ordinal) for attempt in restored.attempts] == [
        ("node-codec-fixed", 1),
        ("node-evidence-fixed", 1),
    ]
    assert restored.attempts[0].status is AttemptStatus.CANCELLED
    assert restored.attempts[0].finished_at == _FINISHED
    assert restored.attempts[1].status is AttemptStatus.COMPLETED
    assert restored.graph_state.active_node_ids == ("evidence-node",)
    assert restored.version == 1

    if cause is not None:
        typed = model_of(DurableRunRecord, json_of(record)).attempts[0]
        assert typed.cancellation_cause is cause  # type: ignore[attr-defined]


@pytest.mark.parametrize("cause", _CAUSE_PARAMS)
def test_cause_round_trip_preserves_nonfinite_physical_evidence(
    cause: CancellationCause | None,
) -> None:
    """Canonical tagged NaN/+Inf/-Inf evidence restores semantically, not as null.

    The Attempt-level codec is the unit the durable stores actually run:
    `json_of` tags non-finite evidence and `model_of` restores it, checked with
    the existing evidence-aware comparison (`evidence_values_equal`) because
    NaN is not equal to itself. A typed cause survives alongside it.
    """
    attempt = _evidence_attempt(cause)

    payload = json.loads(json_of(attempt))
    assert payload["result"]["probe"] == {NON_FINITE_TAG: "nan"}
    assert payload["result"]["positive-infinity"] == {NON_FINITE_TAG: "inf"}
    assert payload["result"]["negative-infinity"] == {NON_FINITE_TAG: "-inf"}
    assert payload["result"]["nested"]["none"] is None
    assert payload["result"]["nested"]["values"][0] == {NON_FINITE_TAG: "nan"}
    assert payload["result"]["nested"]["values"][1] == 2
    assert payload["result"]["finite"] == 1.5
    assert payload["metrics"]["score"] == {NON_FINITE_TAG: "inf"}
    assert payload["metrics"]["count"] == 2
    assert payload["metrics"]["optional"] is None
    assert payload["ordinal"] == 1
    assert payload["created_at"] == "2026-10-03T12:00:00Z"
    assert payload["finished_at"] == "2026-10-03T12:00:10Z"
    for key in ("execution_lease", "deadline_at", "resume_checkpoint_id", "error"):
        assert payload[key] is None

    restored = model_of(Attempt, json_of(attempt))
    evidence = restored.result
    assert evidence is not None
    assert math.isnan(evidence["probe"])
    assert math.isinf(evidence["positive-infinity"]) and evidence["positive-infinity"] > 0
    assert math.isinf(evidence["negative-infinity"]) and evidence["negative-infinity"] < 0
    assert math.isnan(evidence["nested"]["values"][0])
    assert evidence["nested"]["none"] is None
    assert evidence["finite"] == 1.5
    assert math.isinf(restored.metrics["score"]) and restored.metrics["score"] > 0
    assert restored.metrics["count"] == 2
    # Semantic restoration: NaN != NaN; the evidence-aware comparison
    # is what the domain accepts.
    assert evidence["probe"] != _NON_FINITE_RESULT["probe"]
    assert evidence_values_equal(evidence, _NON_FINITE_RESULT)
    assert evidence_values_equal(restored.metrics, _NON_FINITE_METRICS)
    assert restored == attempt
    if cause is not None:
        assert restored.cancellation_cause is cause  # type: ignore[attr-defined]


@pytest.mark.parametrize("cause", _CAUSE_PARAMS)
def test_codec_transport_shapes_preserve_identical_attempt(
    cause: CancellationCause | None,
) -> None:
    """dict/str/bytes/bytearray inputs hydrate to the identical Attempt.

    `decode_payload` must accept however a pool hands a stored payload over,
    and a typed cause must rehydrate through every selected shape — a shape
    that silently stripped the cause (or any other field) would fail here.
    """
    attempt = _fixture_attempt(cause)
    payload = payload_of(attempt)
    text = json_of(attempt)
    encoded = text.encode("utf-8")

    for raw in (payload, text, encoded, bytearray(encoded)):
        assert decode_payload(raw) == payload
        assert model_of(Attempt, raw) == attempt
    assert model_of_json(Attempt, text) == attempt
    assert model_of_json(Attempt, encoded) == attempt
    for transport in _TRANSPORT_IDS:
        assert _codec_round_trip(Attempt, attempt, transport) == attempt
    if cause is not None:
        for transport in _TRANSPORT_IDS:
            restored = _codec_round_trip(Attempt, attempt, transport)
            assert restored.cancellation_cause is cause  # type: ignore[attr-defined]


_INVALID_PAYLOAD_CASES: list[tuple[str, dict[str, Any]]] = [
    ("unknown-value", {"cancellation_cause": "unknown"}),
    ("wrong-type", {"cancellation_cause": 7}),
    ("non-cancelled-typed-cause", {"status": "completed", "cancellation_cause": "requested"}),
    ("unexpected-extra-field", {"unrelated_extra": "keep-me"}),
]


@pytest.mark.parametrize(
    ["case_id", "mutation"],
    _INVALID_PAYLOAD_CASES,
    ids=[case_id for case_id, _ in _INVALID_PAYLOAD_CASES],
)
def test_invalid_cause_and_extra_fields_still_fail_after_decode(
    case_id: str, mutation: dict[str, Any]
) -> None:
    """Decoding must not launder an invalid payload into a valid Attempt.

    Unknown cause values, wrong types, a typed cause on a non-CANCELLED
    status, and unexpected extra fields must still be rejected after decoding,
    and `decode_payload` itself must not silently strip the offending key on
    any input shape.
    """
    raw = {**_LEGACY_PAYLOAD, **mutation}
    text = json.dumps(raw)
    for shape in (raw, text, text.encode("utf-8"), bytearray(text.encode("utf-8"))):
        decoded = decode_payload(shape)
        for key in mutation:
            assert key in decoded
        with pytest.raises(ValidationError, match="|".join(mutation)):
            model_of(Attempt, shape)
