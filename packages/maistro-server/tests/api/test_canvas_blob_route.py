"""Authorized Canvas blob bytes route (ADR-045 presentation surface, #2311).

The governed image path stores generated bytes as internal ``canvas_blobs``
references. Storage references are not URLs, so the boundary owns two halves,
both pinned here:

1. ``GET /v2/canvas/blobs/{blob_id}`` — the one bytes door. Same bearer auth
   as every other route; authorization anchors on the Workspace/Project scope
   the governed egress stamped into the blob's metadata at write time, and
   reads that scope through the canonical Workspace authorizer. A foreign
   member, a revoked member and a guessed id all read as absent (404); a
   blob with no scope stamp fails closed (404); a deployment with no
   Workspace store answers 503 rather than guessing.

2. Layer serialization on ``GET /v2/canvas/designs/{id}`` — the internal
   reference becomes the presentation path there, so an ``<img src>`` never
   receives a bare UUID as a URL. The negative half of that contract is
   asserted too: if the boundary ever regresses to serving the raw
   reference as the URL, these tests fail.
"""

from __future__ import annotations

import uuid
from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

import pytest
from fastapi import FastAPI
from httpx import ASGITransport, AsyncClient

from maistro.config.settings import Settings, get_settings
from maistro.workspaces.model import WorkspaceRole
from maistro.workspaces.store import InMemoryWorkspaceStore
from maistro_server.api.canvas import router as canvas_router
from maistro_server.api.workspace_access import configure_workspace_store

BLOB_PATH = "/v2/canvas/blobs"

WS = "ws-canvas"
OWNER = "owner-1"
MEMBER = "member-1"
FOREIGN = "foreign-1"

PNG_BYTES = b"\x89PNG\r\n\x1a\nfake-bytes"


# ── Fakes ─────────────────────────────────────────────────────────────


class FakeBlob:
    """Structural stand-in for ``maistro_canvas.canvas.store.CanvasBlobRecord``."""

    def __init__(
        self,
        blob_id: str,
        data: bytes,
        format: str,
        metadata: dict[str, Any] | None = None,
    ) -> None:
        self.id = blob_id
        self.data = data
        self.format = format
        self.metadata = metadata if metadata is not None else {}


@dataclass
class FakeCanvas:
    """Structural subset of ``CanvasRecord`` (attributes + ``to_dict``)."""

    id: str
    name: str
    width: int
    height: int
    background_color: str
    org_id: str
    archived_at: datetime | None = None
    created_at: datetime = field(default_factory=datetime.now)
    updated_at: datetime = field(default_factory=datetime.now)

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "width": self.width,
            "height": self.height,
            "background_color": self.background_color,
            "org_id": self.org_id,
            "archived_at": self.archived_at,
        }


@dataclass
class FakeLayer:
    image_path: str | None
    image_url: str | None
    id: str
    canvas_id: str
    name: str
    layer_type: str
    org_id: str
    created_at: datetime = field(default_factory=datetime.now)
    updated_at: datetime = field(default_factory=datetime.now)

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "canvas_id": self.canvas_id,
            "name": self.name,
            "layer_type": self.layer_type,
            "org_id": self.org_id,
            "image_path": self.image_path,
            "image_url": self.image_url,
        }


class FakeCanvasStore:
    """In-memory subset of PgCanvasStore: blobs plus one canvas/layer tree."""

    def __init__(self) -> None:
        self.blobs: dict[str, FakeBlob] = {}
        self.canvases: dict[str, FakeCanvas] = {}
        self.layers: dict[str, list[FakeLayer]] = {}

    async def store_blob(
        self, data: bytes, *, format: str, metadata: dict[str, Any] | None = None
    ) -> str:
        blob_id = str(uuid.uuid4())
        self.blobs[blob_id] = FakeBlob(blob_id, data, format, metadata)
        return blob_id

    async def read_blob(self, blob_id: str) -> FakeBlob | None:
        return self.blobs.get(blob_id)

    async def get_blob(self, blob_id: str) -> bytes | None:
        record = self.blobs.get(blob_id)
        return record.data if record is not None else None

    async def create_canvas(
        self, *, name: str, width: int, height: int, org_id: str, background_color: str = ""
    ) -> FakeCanvas:
        canvas = FakeCanvas(
            id=str(uuid.uuid4()),
            name=name,
            width=width,
            height=height,
            background_color=background_color or "#FFFFFF",
            org_id=org_id,
        )
        self.canvases[canvas.id] = canvas
        self.layers[canvas.id] = []
        return canvas

    async def get_canvas(self, canvas_id: str, *, org_id: str) -> FakeCanvas | None:
        record = self.canvases.get(canvas_id)
        if record is None or record.org_id != org_id:
            return None
        return record

    async def list_layers(self, canvas_id: str, *, org_id: str) -> list[FakeLayer]:
        return [layer for layer in self.layers.get(canvas_id, []) if layer.org_id == org_id]

    async def add_layer(
        self, canvas_id: str, *, name: str, layer_type: str, org_id: str
    ) -> FakeLayer:
        layer = FakeLayer(
            id=str(uuid.uuid4()),
            canvas_id=canvas_id,
            name=name,
            layer_type=layer_type,
            org_id=org_id,
            image_path=None,
            image_url=None,
        )
        self.layers[canvas_id].append(layer)
        return layer


