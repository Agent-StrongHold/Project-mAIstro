def _make_app(store: FakeCanvasStore | None, api_keys: list[str] | None = None) -> FastAPI:
    app = FastAPI()
    app.include_router(canvas_router)
    if store is not None:
        app.state.canvas_store = store
    app.dependency_overrides[get_settings] = lambda: Settings(api_keys=api_keys or [])
    return app


async def _client(
    store: FakeCanvasStore | None = None, api_keys: list[str] | None = None
) -> AsyncClient:
    transport = ASGITransport(app=_make_app(store, api_keys))
    return AsyncClient(transport=transport, base_url="http://testserver")


def _bearer(secret: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {secret}"}


async def _seed_scoped_blob(store: FakeCanvasStore, **scope: str) -> str:
    """A blob written the way the governed egress writes it (scope stamp on)."""
    metadata: dict[str, Any] = {"source": "governed-image-egress"}
    metadata.update(scope)
    return await store.store_blob(PNG_BYTES, format="image/png", metadata=metadata)


async def _seed_canvas_layer(store: FakeCanvasStore, ref: str) -> str:
    canvas = await store.create_canvas(name="c", width=8, height=8, org_id="dev")
    layer = await store.add_layer(canvas.id, name="sky", layer_type="background", org_id="dev")
    layer.image_path = ref
    return canvas.id


# ── 1. The authorized bytes door ──────────────────────────────────────


class TestAuthorizedBlobBytes:
    async def test_workspace_owner_gets_bytes_with_the_stored_media_type(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id=WS, project_id="proj-1")
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 200
        assert response.content == PNG_BYTES
        assert response.headers["content-type"] == "image/png"
        # Byte immutability is not read authority: caching would let a
        # revoked member (or a different bearer sharing the browser cache)
        # keep loading past the membership check, so nothing is stored.
        assert response.headers["cache-control"] == "no-store"

    async def test_workspace_member_gets_bytes_too(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        async with await _client(store, api_keys=[f"{MEMBER}:member-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("member-secret"))
        assert response.status_code == 200
        assert response.content == PNG_BYTES

    async def test_auth_disabled_dev_owner_reads_the_provisioned_workspace_scope(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        # The default deployment provisions its configured Workspace with the
        # "dev" owner; the auth-disabled principal IS dev, so the shipped
        # single-operator path keeps working without any key configured.
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        async with await _client(store) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}")
        assert response.status_code == 200
        assert response.content == PNG_BYTES

    async def test_a_foreign_principal_reads_absence(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        # Authenticated but not a member of the blob's Workspace: the blob
        # reads as absent — never as a filtered row.
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        async with await _client(store, api_keys=[f"{FOREIGN}:foreign-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("foreign-secret"))
        assert response.status_code == 404

    async def test_a_revoked_member_reads_absence(
        self,
        store: FakeCanvasStore,
        workspace_store: InMemoryWorkspaceStore,
        workspace: None,
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        await workspace_store.remove_membership(WS, user_id=MEMBER)
        async with await _client(store, api_keys=[f"{MEMBER}:member-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("member-secret"))
        assert response.status_code == 404

    async def test_a_guessed_blob_id_reads_absence(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(
                f"{BLOB_PATH}/{uuid.uuid4()}", headers=_bearer("owner-secret")
            )
        assert response.status_code == 404

    async def test_a_blob_without_a_scope_stamp_fails_closed(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        # A write that cannot name its authority is never served — not even
        # to the Workspace owner.
        ref = await _seed_scoped_blob(store)
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 404

    async def test_a_blob_scoped_to_another_workspace_is_not_ours(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id="ws-other", project_id="p")
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 404

    async def test_unauthenticated_with_auth_enabled_is_401(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}")
        assert response.status_code == 401

    async def test_no_workspace_store_configured_answers_503(self, store: FakeCanvasStore) -> None:
        # Fail truthfully on the missing authorization authority rather than
        # serving bytes nobody vouched for.
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 503

    async def test_no_canvas_store_configured_answers_503(self, workspace: None) -> None:
        async with await _client(None) as client:
            response = await client.get(f"{BLOB_PATH}/{uuid.uuid4()}")
        assert response.status_code == 503

    async def test_a_store_without_whole_row_reads_answers_503(self, workspace: None) -> None:
        # A store that can hand back bytes but not identity cannot authorize
        # a read: 503 (the wiring gap), not a fabricated 404.
        class BytesOnlyStore(FakeCanvasStore):
            read_blob = None  # type: ignore[assignment]

        ref = await _seed_scoped_blob(FakeCanvasStore(), workspace_id=WS)
        async with await _client(BytesOnlyStore(), api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 503

    async def test_blank_format_serves_octet_stream(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await store.store_blob(b"raw", format="", metadata={"workspace_id": WS})
        async with await _client(store, api_keys=[f"{OWNER}:owner-secret"]) as client:
            response = await client.get(f"{BLOB_PATH}/{ref}", headers=_bearer("owner-secret"))
        assert response.status_code == 200
        assert response.headers["content-type"] == "application/octet-stream"


# ── 2. The reference/URL distinction at the boundary ──────────────────


class TestLayerSerializationPresentsUrls:
    async def test_blob_ref_serializes_as_the_presentation_url(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        canvas_id = await _seed_canvas_layer(store, ref)
        async with await _client(store) as client:
            response = await client.get(f"/v2/canvas/designs/{canvas_id}")
        assert response.status_code == 200
        serialized = response.json()["layers"][0]
        # The browser gets a loadable URL, never the bare reference — this is
        # the negative test: a boundary that regresses to serving the raw
        # UUID-as-URL fails right here.
        assert serialized["image_path"] == f"{BLOB_PATH}/{ref}"
        assert serialized["image_path"] != ref

    async def test_non_ref_image_values_pass_through_untouched(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        canvas_id = await _seed_canvas_layer(store, "data:image/png;base64,aGVsbG8=")
        store.layers[canvas_id][0].image_url = "https://cdn.example.com/legacy.png"
        async with await _client(store) as client:
            response = await client.get(f"/v2/canvas/designs/{canvas_id}")
        assert response.status_code == 200
        serialized = response.json()["layers"][0]
        assert serialized["image_path"] == "data:image/png;base64,aGVsbG8="
        assert serialized["image_url"] == "https://cdn.example.com/legacy.png"

    async def test_the_full_presentation_url_resolves_back_to_the_bytes(
        self, store: FakeCanvasStore, workspace: None
    ) -> None:
        # Round trip: what the design serializer emits is exactly what the
        # bytes door serves — one seam, no second URL dialect.
        ref = await _seed_scoped_blob(store, workspace_id=WS)
        canvas_id = await _seed_canvas_layer(store, ref)
        async with await _client(store) as client:
            design = await client.get(f"/v2/canvas/designs/{canvas_id}")
            served = await client.get(design.json()["layers"][0]["image_path"])
        assert served.status_code == 200
        assert served.content == PNG_BYTES
